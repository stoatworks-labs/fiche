int GlyphOf( char c )
{
	const char upper = static_cast< char >( std::toupper( static_cast< unsigned char >( c ) ) );
	const char* at   = upper != '\0' ? std::strchr( kCharacters, upper ) : nullptr;
	const int index  = at ? static_cast< int >( at - kCharacters ) : 0;
	return index < kDefined ? index : 0;
}

std::vector< int > Encode( const std::string& title, int limit )
{
	std::vector< int > out;
	for( char c : title )
	{
		if( static_cast< int >( out.size() ) >= limit )
			break;
		out.push_back( GlyphOf( c ) );
	}
	// Trailing spaces draw nothing and cost a lookup.
	while( !out.empty() && out.back() == 0 )
		out.pop_back();
	return out;
}

std::vector< Level > BuildAtlas()
{
	std::vector< Level > levels;
	Level base { kGlyphs * kCell, kCell, {} };
	base.texels.assign( static_cast< size_t >( base.width ) * base.height, 0 );
	for( int g = 0; g < kDefined; ++g )
		for( int row = 0; row < 7; ++row )
			for( int col = 0; col < 5; ++col )
				if( kRows[ g ][ row ] & ( 0x10 >> col ) )
					base.texels[ static_cast< size_t >( 1 + row ) * base.width + g * kCell + 1 + col ] = 255;
	levels.push_back( base );
	// Box mips while the cell is still more than one texel tall.
	while( levels.back().height > 1 )
	{
		const Level& from = levels.back();
		Level next { from.width / 2, from.height / 2, {} };
		next.texels.assign( static_cast< size_t >( next.width ) * next.height, 0 );
		for( int y = 0; y < next.height; ++y )
			for( int x = 0; x < next.width; ++x )
			{
				int sum = 0;
				for( int j = 0; j < 2; ++j )
					for( int i = 0; i < 2; ++i )
						sum += from.texels[ static_cast< size_t >( 2 * y + j ) * from.width + 2 * x + i ];
				next.texels[ static_cast< size_t >( y ) * next.width + x ] = static_cast< unsigned char >( ( sum + 2 ) / 4 );
			}
		levels.push_back( next );
	}
	return levels;
}

